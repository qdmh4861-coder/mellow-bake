export function storyContent(product) {
  const id = equivalent[product.id] || product.id
  const [headline, featureText] = accents[id] || [`${product.koreanName}의 맛있는 순간`,product.description]
  const ingredients = ingredientWords.filter(word=>product.description.includes(word)).filter((word,_,all)=>!all.some(other=>other!==word&&other.includes(word)))
  const flavor = ingredients.length ? ingredients.slice(0,3).join(' · ') : product.koreanName
  const family = families.find(([pattern])=>pattern.test(product.name)) || [null,'bread',['반죽 재료 준비','성형과 발효','굽기와 마무리']]
  const category = {bread:'빵',cake:'케이크',sandwich:'샌드위치',drink:'음료'}[product.category]
  const drink = product.category==='drink'
  const processText = family[1]==='sandwich'
    ? [`${flavor} 등 상품 설명에 등장하는 속재료를 살펴보는 단계입니다.`,`${product.koreanName}의 빵과 속재료가 어울리는 구성을 표현합니다.`,`${featureText} 이 조합을 완성 컷으로 보여주는 연출입니다.`]
    : drink ? [`${flavor}의 향과 색을 담을 재료 구성을 살펴봅니다.`,`${family[1]==='blended'?'스무디의 부드러운 질감':family[1]==='ade'?'과일과 탄산의 조화':'음료의 향과 맛'}를 표현하는 디자인용 단계입니다.`,`${product.koreanName} 한 잔의 모습을 담는 마무리 연출입니다.`]
      : [`${flavor}의 맛을 표현할 재료 구성을 살펴봅니다.`,`${family[1]==='pastry'?'겹겹의 결':family[1]==='mousse'?'부드러운 크림 층':family[1]==='cake'?'시트와 크림의 조합':'빵의 형태와 속재료'}를 보여주는 디자인용 단계입니다.`,`${product.koreanName}의 완성 모습을 담는 연출입니다. 실제 제조 기준은 확인이 필요합니다.`]
  return { headline, featureTitle:drink?'한 모금에 담긴 향과 풍미':'한 입에 담긴 식감과 풍미', signatureTitle:headline, signatureText:product.description, featureText, ingredients,
    materialsTitle:`${flavor}의 맛을 만나다`, materialsText:`상품명과 설명에서 소개한 맛의 요소는 ${flavor}입니다. 실제 원재료 구성과 함량을 확정한 정보는 아닙니다.`,
    process:family[2].map((title,i)=>({title,text:processText[i],image:`process-${i+1}`})),
    enjoy:[{title:drink?'첫 모금의 향':'첫 입의 풍미',text:featureText},{title:drink?'한 잔의 조화':'함께 즐기는 조합',text:drink?`${flavor}의 맛을 천천히 느끼며 티타임을 즐겨보세요.`:`${flavor}의 풍미를 느끼며 취향에 맞는 음료를 곁들여 보세요.`},{title:'나를 위한 작은 여유',text:`${product.koreanName}${drink?' 한 잔':' 한 조각'}과 함께 잠시 쉬어가는 시간을 만들어보세요.`}],
    charms:[{title:drink?'향으로 기억하는 한 잔':family[1]==='pastry'?'겹을 따라 느끼는 빵의 결':family[1]==='sandwich'?'속재료를 나란히 담은 한 입':'식감으로 느끼는 작은 즐거움',text:drink?`${flavor}의 향과 색을 살펴보며 한 잔을 천천히 즐겨보세요.`:`${flavor}과 ${category}의 조합을 눈으로도 느껴보세요. 상세 이미지는 식감과 형태가 잘 보이는 다른 구도로 준비합니다.`},{title:`${flavor}의 균형`,text:`${category}에 담긴 각각의 맛과 질감을 함께 살펴보세요. 상품 설명에 소개된 조합을 다른 구도의 이미지로 보여주는 영역입니다.`},{title:`${product.koreanName}과 함께하는 시간`,text:drink?'좋아하는 잔에 담아 천천히 향과 맛을 즐겨보세요.':'좋아하는 사람과 나누거나, 혼자만의 간식 시간에 차분히 즐겨보세요.'}],
    storage:[['보관 방법',`${product.koreanName}의 냉장·냉동 가능 여부와 정확한 보관 조건은 상품 표시사항 확인이 필요합니다.`],['소비기한',`${category}의 제조일과 소비기한, 개봉 후 섭취 기준을 확인한 후 안내합니다.`],['섭취 안내',drink?'음료의 권장 음용 온도와 시간은 확인 중입니다.':'가열 가능 여부와 권장 섭취 방법은 확인 중입니다.']],
    recipeNote:'제작 과정과 즐기는 방법은 상품 설명을 바탕으로 구성한 디자인용 예시입니다. 실제 제조법·보관 기준·성분을 확정한 안내가 아닙니다.' }
}
